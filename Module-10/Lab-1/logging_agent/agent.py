import asyncio
from google.adk.agents import Agent
from google.adk.agents.callback_context import CallbackContext
from google.adk.models.llm_request import LlmRequest
from google.adk.models.llm_response import LlmResponse
from google.adk.sessions import InMemorySessionService
from google.adk.runners import Runner
from google.genai import types
from typing import Optional

from dotenv import load_dotenv
load_dotenv()

# --- Model Callbacks Demo ---
# ADK provides two callback points around the LLM call:
#
# 1. before_model_callback — fires BEFORE each LLM call
#    Signature: (CallbackContext, LlmRequest) -> Optional[LlmResponse]
#    Return None → proceed to LLM | Return LlmResponse → skip the LLM call
#
# 2. after_model_callback — fires AFTER each LLM response
#    Signature: (CallbackContext, LlmResponse) -> Optional[LlmResponse]
#    Return None → keep original response | Return LlmResponse → replace it

# --- Tracking data ---
callback_log = []
response_metrics = []

DISCLAIMER = "\n\n_[Disclaimer: This response was generated by AI and may not be 100% accurate.]_"


# =============================================
# CALLBACK 1: Before Model — Request Logging
# =============================================
def log_request(
    callback_context: CallbackContext, llm_request: LlmRequest
) -> Optional[LlmResponse]:
    """Logs every LLM request before it's sent."""
    agent_name = callback_context.agent_name

    # Extract the latest user message
    last_user_message = ""
    if llm_request.contents:
        for content in reversed(llm_request.contents):
            if content.role == "user" and content.parts:
                if content.parts[0].text:
                    last_user_message = content.parts[0].text
                    break

    total_messages = len(llm_request.contents) if llm_request.contents else 0

    log_entry = {
        "agent": agent_name,
        "total_messages": total_messages,
        "last_user_message": last_user_message[:80],
    }
    callback_log.append(log_entry)

    print(f"\n  [BEFORE MODEL] Messages in context: {total_messages}")
    print(f"  [BEFORE MODEL] Latest user message: '{last_user_message[:80]}'")

    return None  # Proceed to LLM


# =============================================
# CALLBACK 2: After Model — Response Monitor
# =============================================
def monitor_response(
    callback_context: CallbackContext, llm_response: LlmResponse
) -> Optional[LlmResponse]:
    """Monitors every LLM response, collects metrics, appends a disclaimer."""

    # Extract the response text
    response_text = ""
    if llm_response.content and llm_response.content.parts:
        for part in llm_response.content.parts:
            if part.text:
                response_text += part.text

    # Collect metrics
    word_count = len(response_text.split())
    char_count = len(response_text)

    response_metrics.append({
        "word_count": word_count,
        "char_count": char_count,
        "preview": response_text[:60],
    })

    print(f"  [AFTER MODEL] Response length: {word_count} words, {char_count} chars")

    # Append disclaimer to every response
    if response_text:
        modified_text = response_text + DISCLAIMER
        print(f"  [AFTER MODEL] Disclaimer appended.")

        return LlmResponse(
            content=types.Content(
                role="model",
                parts=[types.Part(text=modified_text)],
            )
        )

    return None


# --- Define the Agent with BOTH callbacks ---
agent = Agent(
    name="logging_agent",
    model="gemini-2.5-flash",
    description="A helpful assistant with request logging and response monitoring.",
    instruction="""You are a concise assistant. Answer questions in 1-2 sentences.""",
    before_model_callback=log_request,
    after_model_callback=monitor_response,
)

# --- Session and Runner setup ---
session_service = InMemorySessionService()
APP_NAME = "model_callbacks_demo"
USER_ID = "user_1"
SESSION_ID = "session_001"

asyncio.run(
    session_service.create_session(
        app_name=APP_NAME, user_id=USER_ID, session_id=SESSION_ID
    )
)

runner = Runner(agent=agent, app_name=APP_NAME, session_service=session_service)


def call_agent(query):
    """Send a message and print the response."""
    print(f"\n>>> User: {query}")
    message = types.Content(role="user", parts=[types.Part(text=query)])

    final_response = "No response received."
    for event in runner.run(user_id=USER_ID, session_id=SESSION_ID, new_message=message):
        if event.is_final_response():
            if event.content and event.content.parts:
                final_response = event.content.parts[0].text

    print(f"<<< Agent: {final_response}")


# =============================================
# PART 1: See both callbacks in action
# =============================================
print("=" * 60)
print("Model Callbacks — Request Logging & Response Monitoring")
print("=" * 60)
print("Watch [BEFORE MODEL] and [AFTER MODEL] logs around each response.")

call_agent("What is the speed of light?")
call_agent("How far is the Moon from Earth?")
call_agent("What causes earthquakes?")

# =============================================
# PART 2: Review collected data
# =============================================
print("\n" + "=" * 60)
print("Reviewing callback data")
print("=" * 60)

print(f"\n--- Request Log (before_model_callback) ---")
print(f"Total LLM calls intercepted: {len(callback_log)}")
for i, entry in enumerate(callback_log):
    print(f"  Call {i + 1}: {entry['total_messages']} messages in context | '{entry['last_user_message']}'")

print(f"\n--- Response Metrics (after_model_callback) ---")
total_words = sum(m["word_count"] for m in response_metrics)
for i, metric in enumerate(response_metrics):
    print(f"  Response {i + 1}: {metric['word_count']} words, {metric['char_count']} chars")
print(f"  Average: {total_words // len(response_metrics)} words per response")

print("\nNotice: message count grows each turn (the callback sees full history).")
print("Every response includes a disclaimer added by after_model_callback.")


